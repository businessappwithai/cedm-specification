#!/usr/bin/env bun
/**
 * Build domain/enumerations/index.yaml: one entry per enumerated attribute.
 *
 * Every enumeration has a business table in a generated application (see
 * specification/enumeration-semantics.yaml). The registry is the list of them,
 * derived from the entity files, and `tools/validate.ts` fails when it is stale.
 *
 *     bun tools/build-enumerations.ts [--check]
 */

import "./lib/cli";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { enumerationName } from "./lib/dictionary";
import { loadEntities, ROOT, relative } from "./lib/library";
import { flowScalar } from "./lib/scalar";
import { str } from "./lib/text";
import type { Spec } from "./lib/yaml";

export const REGISTRY_FILE = path.join(ROOT, "domain", "enumerations", "index.yaml");

interface Enumeration {
  name: string;
  entity: string;
  attribute: string;
  values: string[];
}

/** Every enumerated attribute; `entities` defaults to the library on disk. */
export function collect(
  entities: Spec[] = loadEntities().map((file) => file.entity)
): Enumeration[] {
  const rows: Enumeration[] = [];
  for (const entity of entities) {
    for (const attr of entity.attributes ?? []) {
      if (!attr.values?.length) continue;
      rows.push({
        name: enumerationName(entity.name, attr.name),
        entity: entity.name,
        attribute: attr.name,
        values: attr.values.map(str),
      });
    }
  }
  return rows.sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
}

export function render(rows: Enumeration[]): string {
  const out = [
    "# Generated by tools/build-enumerations.ts — do not edit.",
    "# One business table per enumeration; see specification/enumeration-semantics.yaml.",
    "registry:",
    `  count: ${rows.length}`,
    "  enumerations:",
  ];
  for (const row of rows) {
    out.push(`    - name: ${row.name}`);
    out.push(`      entity: ${row.entity}`);
    out.push(`      attribute: ${row.attribute}`);
    out.push(`      values: [${row.values.map(flowScalar).join(", ")}]`);
  }
  return `${out.join("\n")}\n`;
}

/** Null when the registry is current, otherwise why it is not. */
export function staleness(entities?: Spec[]): string | null {
  const text = render(collect(entities));
  if (existsSync(REGISTRY_FILE) && readFileSync(REGISTRY_FILE, "utf-8") === text) return null;
  return `${relative(REGISTRY_FILE)} is stale: run bun tools/build-enumerations.ts`;
}

if (import.meta.main) {
  if (process.argv.includes("--check")) {
    const stale = staleness();
    console.log(
      stale ?? `${path.relative(ROOT, REGISTRY_FILE)} is current (${collect().length} enumerations)`
    );
    process.exit(stale ? 1 : 0);
  }
  const rows = collect();
  mkdirSync(path.dirname(REGISTRY_FILE), { recursive: true });
  writeFileSync(REGISTRY_FILE, render(rows));
  console.log(`${rows.length} enumerations`);
}
