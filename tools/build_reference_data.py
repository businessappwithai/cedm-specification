#!/usr/bin/env python3
"""Build domain/reference-data/*.yaml: the shared geography, money and language lists.

Every generated application ships the same Country, StateProvince, City, Currency
and Language rows, because they come from the common CEDM specification and not
from each application's author. The sources are public registries read through
pycountry (ISO 3166-1 countries, ISO 3166-2 subdivisions, ISO 4217 currencies,
ISO 639-1 languages) and geonamescache (GeoNames cities, with the national
capitals and every city of 750 thousand or more). The checked-in files are the
specification; this tool is how they were made, and a run reproduces them.

Subdivisions are the first level of the countries in SUBDIVISION_COUNTRIES —
the whole ISO table is five thousand rows, and an application that needs another
country's states adds them as rows of its own. Cities link to a state or province
where the registry says which: the United States and Canada (GeoNames numbers
Canada's provinces, and CANADA maps them to ISO 3166-2); elsewhere the state is
left empty and the city belongs to its country alone.

    pip install pycountry geonamescache
    python tools/build_reference_data.py
"""
from __future__ import annotations

import json
import pathlib

import geonamescache
import pycountry

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "domain" / "reference-data"

SUBDIVISION_COUNTRIES = [
    "US", "CA", "MX", "BR", "AR", "CL", "CO", "PE", "AU", "NZ", "IN", "CN", "JP", "KR", "ID", "PH", "TH",
    "VN", "MY", "SG", "PK", "BD", "GB", "IE", "DE", "FR", "ES", "IT", "NL", "BE", "CH", "AT", "SE", "NO",
    "DK", "FI", "PL", "PT", "ZA", "NG", "KE", "EG", "AE", "SA", "TR", "RU", "UA",
]
CANADA = {"01": "AB", "02": "BC", "03": "MB", "04": "NB", "05": "NL", "07": "NS", "08": "ON", "09": "PE",
          "10": "QC", "11": "SK", "12": "YT", "13": "NT", "14": "NU"}
ZERO = {"BIF", "CLP", "DJF", "GNF", "ISK", "JPY", "KMF", "KRW", "PYG", "RWF", "UGX", "UYI", "VND", "VUV", "XAF", "XOF", "XPF"}
THREE = {"BHD", "IQD", "JOD", "KWD", "LYD", "OMR", "TND"}


# ISO 639-1 languages written right to left in their usual script (Unicode CLDR).
RIGHT_TO_LEFT = {"ar", "dv", "fa", "he", "ks", "ku", "ps", "sd", "ug", "ur", "yi"}


def _slug(name: str) -> str:
    """`Rio de Janeiro` → `RIO-DE-JANEIRO`; accents folded, anything else dropped."""
    import re
    import unicodedata

    plain = unicodedata.normalize("NFKD", name).encode("ascii", "ignore").decode()
    return re.sub(r"[^A-Z0-9]+", "-", plain.upper()).strip("-") or "CITY"


def _number(value: float) -> float | int:
    rounded = round(value, 4)
    return int(rounded) if rounded == int(rounded) else rounded


def write(name: str, entity: str, key: str, source: str, rows: list[dict]) -> None:
    lines = [
        f"# {entity} — reference data of the common CEDM specification.",
        f"# Source: {source}",
        "# Generated by tools/build_reference_data.py — do not edit; rerun the tool.",
        "referenceData:",
        f"  entity: {entity}",
        f"  key: {key}",
        f"  count: {len(rows)}",
        "  rows:",
    ]
    lines += ["    - " + json.dumps(row, ensure_ascii=False, separators=(", ", ": ")) for row in rows]
    (OUT / f"{name}.yaml").write_text("\n".join(lines) + "\n")
    print(f"{entity}: {len(rows)} rows")


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    gc = geonamescache.GeonamesCache()
    info = gc.get_countries()

    currencies = sorted(pycountry.currencies, key=lambda c: c.alpha_3)
    write("currency", "Currency", "code", "ISO 4217 (pycountry)", [
        {"code": c.alpha_3, "name": c.name, "decimalPlaces": 0 if c.alpha_3 in ZERO else 3 if c.alpha_3 in THREE else 2, "status": "ACTIVE"}
        for c in currencies
    ])
    known = {c.alpha_3 for c in currencies}

    countries = sorted(pycountry.countries, key=lambda c: c.alpha_2)
    rows = []
    for c in countries:
        g = info.get(c.alpha_2, {})
        row = {"code": c.alpha_2, "alpha3": c.alpha_3, "numericCode": c.numeric, "name": c.name}
        if g.get("phone"):
            row["phoneCode"] = str(g["phone"]).split(",")[0].strip()
        if g.get("currencycode") in known:
            row["currency"] = g["currencycode"]
        rows.append(row)
    write("country", "Country", "code", "ISO 3166-1 (pycountry), GeoNames country info", rows)

    languages = sorted((l for l in pycountry.languages if hasattr(l, "alpha_2")), key=lambda l: l.alpha_2)
    write(
        "language",
        "Language",
        "code",
        "ISO 639-1 and 639-3 (pycountry); script direction from Unicode CLDR",
        [
            {"code": l.alpha_2, "alpha3": l.alpha_3, "name": l.name, "direction": "RTL" if l.alpha_2 in RIGHT_TO_LEFT else "LTR"}
            for l in languages
        ],
    )

    subdivisions = [s for s in pycountry.subdivisions if s.parent_code is None and s.country_code in SUBDIVISION_COUNTRIES]
    subdivisions.sort(key=lambda s: s.code)
    write("state-province", "StateProvince", "code", "ISO 3166-2 first level (pycountry)", [
        {"code": s.code, "name": s.name, "subdivisionType": s.type, "country": s.country_code} for s in subdivisions
    ])
    state_codes = {s.code for s in subdivisions}

    capitals = {(c, g["capital"]) for c, g in info.items() if g.get("capital")}
    cities = []
    for city in gc.get_cities().values():
        cc = city["countrycode"]
        if cc not in {c.alpha_2 for c in countries}:
            continue
        if city["population"] < 750_000 and (cc, city["name"]) not in capitals:
            continue
        # Several GeoNames places share a capital's name; the most populous is the capital.
        cities.append(city)
    best: dict[tuple[str, str], dict] = {}
    for city in sorted(cities, key=lambda c: -c["population"]):
        best.setdefault((city["countrycode"], city["name"]), city)
    rows = []
    for city in sorted(best.values(), key=lambda c: (c["countrycode"], c["name"])):
        cc, admin = city["countrycode"], city["admin1code"]
        iso = None
        if cc == "US":
            iso = f"US-{admin}"
        elif cc == "CA" and admin in CANADA:
            iso = f"CA-{CANADA[admin]}"
        row = {"code": f"{cc}-{_slug(city['name'])}", "name": city["name"], "country": cc}
        if iso in state_codes:
            row["stateProvince"] = iso
        row["population"] = city["population"]
        # A whole number is written as one (`125`, not `125.0`): the generators read
        # numbers differently and must print the same text.
        row["latitude"] = _number(city["latitude"])
        row["longitude"] = _number(city["longitude"])
        if city["timezone"]:
            row["timezone"] = city["timezone"]
        if (cc, city["name"]) in capitals:
            row["isCapital"] = True
        rows.append(row)
    seen = set()
    for r in rows:
        assert r["code"] not in seen, r["code"]
        seen.add(r["code"])
    write("city", "City", "code", "GeoNames (geonamescache): national capitals and cities of 750 thousand or more", rows)


if __name__ == "__main__":
    main()
