#!/usr/bin/env python3
"""Build domain/enumerations/index.yaml: one entry per enumerated attribute.

Every enumeration has a business table in a generated application (see
specification/enumeration-semantics.yaml). The registry is the list of them,
derived from the entity files, and `tools/validate.py` fails when it is stale.

    python tools/build_enumerations.py [--check]
"""
from __future__ import annotations

import pathlib
import sys

import yaml

sys.path.insert(0, str(pathlib.Path(__file__).parent))
import dictionary_lib as d  # noqa: E402

OUT = d.ROOT / "domain" / "enumerations" / "index.yaml"


def collect() -> list[dict]:
    rows = []
    for path in sorted((d.ROOT / "domain" / "entities").glob("*.yaml")):
        if path.name == "index.yaml":
            continue
        entity = yaml.safe_load(path.read_text())["entity"]
        for attr in entity.get("attributes") or []:
            values = attr.get("values")
            if not values:
                continue
            rows.append(
                {
                    "name": d.enumeration_name(entity["name"], attr["name"]),
                    "entity": entity["name"],
                    "attribute": attr["name"],
                    "values": [str(v) for v in values],
                }
            )
    return sorted(rows, key=lambda r: r["name"])


def render(rows: list[dict]) -> str:
    out = ["# Generated by tools/build_enumerations.py — do not edit.", "# One business table per enumeration; see specification/enumeration-semantics.yaml.", "registry:", f"  count: {len(rows)}", "  enumerations:"]
    for r in rows:
        out.append(f"    - name: {r['name']}")
        out.append(f"      entity: {r['entity']}")
        out.append(f"      attribute: {r['attribute']}")
        out.append("      values: [" + ", ".join(yaml.safe_dump(v, default_flow_style=True).split("\n")[0].removesuffix("...").strip() for v in r["values"]) + "]")
    return "\n".join(out) + "\n"


def main() -> int:
    text = render(collect())
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.relative_to(d.ROOT)} is stale: run tools/build_enumerations.py")
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"{len(collect())} enumerations")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
