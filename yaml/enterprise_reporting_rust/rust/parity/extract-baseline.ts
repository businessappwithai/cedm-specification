/**
 * Regenerate rust/migration/sql/0001_baseline.sql from src/lib/db/bootstrap.ts.
 *
 * The Rust baseline migration must run exactly the DDL the Node bootstrap runs
 * (MIGRATION_PLAN.md §2.2), so it is extracted rather than retyped. Run it
 * whenever bootstrap.ts gains a table, column or index:
 *
 *     bun rust/parity/extract-baseline.ts
 *
 * Only the `tables`, `alters` and `indexes` arrays are taken — the seed rows
 * (admin user, roles, help articles) are data, not schema, and stay with the
 * seeder.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dir, "..", "..");
const source = readFileSync(join(root, "src/lib/db/bootstrap.ts"), "utf8");

function block(name: string): string[] {
  const start = source.indexOf(`const ${name} = [`);
  if (start === -1) throw new Error(`bootstrap.ts has no \`const ${name} = [\``);
  const end = source.indexOf("\n  ];", start);
  const body = source.slice(start, end);
  return [...body.matchAll(/sql`([\s\S]*?)`/g)].map((m) => m[1].trim());
}

const sections = [
  ["tables", block("tables")],
  ["alters", block("alters")],
  ["indexes", block("indexes")],
] as const;

let out =
  "-- GENERATED by rust/parity/extract-baseline.ts from src/lib/db/bootstrap.ts.\n" +
  "-- Do not edit by hand; regenerate. Every statement is idempotent.\n";
for (const [name, statements] of sections) {
  out += `\n-- ── ${name} (${statements.length}) ──\n`;
  for (const s of statements) out += `${s};\n\n`;
}

const target = join(root, "rust/migration/sql/0001_baseline.sql");
writeFileSync(target, out);
console.log(`wrote ${target}: ${sections.map(([n, s]) => `${s.length} ${n}`).join(", ")}`);
