//! `seed/system.sql` — the settings an operator may change without a redeploy.
//!
//! The TypeScript original is
//! `packages/generator/src/generators/tanstack-astryx-loco/system-seed.ts`, and
//! the two must agree byte for byte; `bun run parity` is what says they do.
//!
//! The design note lives in that file and in the m0014 migration. In short:
//! `sys_system` sits above Loco's `settings` block, `services::system_config`
//! resolves DB row -> settings -> compiled default, and every row but the two
//! the model names is seeded empty so applying this file changes no behaviour.

use uuid::Uuid;

use crate::dictionary::{insert, now, text, Sql, NAMESPACE};

/// What a value means to whatever reads it back. The column is always TEXT.
struct Setting {
    key: &'static str,
    data_type: &'static str,
    category: &'static str,
    description: &'static str,
    /// Masked wherever the value is shown. Not encryption — see the migration.
    is_sensitive: bool,
}

/// The settable keys, in the order the admin screen lists them.
///
/// A key belongs here only when something in the generated backend reads it
/// through `system_config`. A row nothing resolves is a setting that appears to
/// work and does nothing, which is worse than an absent one.
const SETTINGS: &[Setting] = &[
    Setting {
        key: "app_name",
        data_type: "string",
        category: "identity",
        description: "The application's name, shown in the sidebar and returned by GET /api/me/health. Changing it renames the running application; it does not rename the database or the crate.",
        is_sensitive: false,
    },
    Setting {
        key: "app_description",
        data_type: "text",
        category: "identity",
        description: "What this application is for. Taken from the model's description and returned by GET /api/me/health.",
        is_sensitive: false,
    },
    Setting {
        key: "ai_base_url",
        data_type: "string",
        category: "ai",
        description: "Base URL of an OpenAI-compatible endpoint for POST /api/ai/query. Empty leaves the add-on answering 503. Set this and ai_model to turn natural-language querying on without restarting.",
        is_sensitive: false,
    },
    Setting {
        key: "ai_model",
        data_type: "string",
        category: "ai",
        description: "Model name asked for the query plan. Required alongside ai_base_url; either one empty leaves the add-on off.",
        is_sensitive: false,
    },
    Setting {
        key: "ai_api_key",
        data_type: "string",
        category: "ai",
        description: "Bearer token for the AI endpoint. A local server that needs none accepts any value.",
        is_sensitive: true,
    },
    Setting {
        key: "electric_url",
        data_type: "string",
        category: "sync",
        description: "ElectricSQL shape-service URL behind GET /api/electric/v1/shape. Empty leaves the proxy answering 503, which is the default.",
        is_sensitive: false,
    },
];

/// How many keys the seed writes. Read by the CLI's log line.
pub const SETTING_COUNT: usize = SETTINGS.len();

pub struct SystemSeedOptions<'a> {
    pub project_name: &'a str,
    /// `%%meta description:`, or the CLI's description when the model has none.
    pub project_description: &'a str,
    /// Value written to every `created_by` / `updated_by`.
    pub created_by: &'a str,
}

/// `seed/system.sql` — one row per settable key.
#[must_use]
pub fn build_system_seed_sql(options: &SystemSeedOptions<'_>) -> String {
    let SystemSeedOptions {
        project_name,
        project_description,
        created_by,
    } = *options;

    let mut out: Vec<String> = Vec::new();

    out.push(format!("-- Settable configuration for {project_name}."));
    out.push("--".to_string());
    out.push(
        "-- Generated by @appwithai/generator — do not edit by hand; regenerate instead."
            .to_string(),
    );
    out.push(
        "-- Applied by `cargo loco task seed_system` and by `cargo loco db seed`.".to_string(),
    );
    out.push("--".to_string());
    out.push(
        "-- Every statement is `ON CONFLICT DO NOTHING` over a deterministic primary".to_string(),
    );
    out.push(
        "-- key and a unique config_key, so running this file twice is a no-op — and".to_string(),
    );
    out.push(
        "-- regenerating an application never overwrites a value an operator set.".to_string(),
    );
    out.push("--".to_string());
    out.push(
        "-- The rows carrying a value are the two the model names. The rest are seeded".to_string(),
    );
    out.push("-- empty on purpose: `system_config` falls through an empty row to the".to_string());
    out.push("-- settings block, so applying this file changes no behaviour at all.".to_string());
    out.push(String::new());

    for setting in SETTINGS {
        let name = format!("{project_name}:system:{}", setting.key);
        let id = Uuid::new_v5(&NAMESPACE, name.as_bytes()).to_string();
        out.push(insert(
            "sys_system",
            &[
                ("sys_system_id", text(id)),
                ("config_key", text(setting.key)),
                (
                    "config_value",
                    text(value_for(setting.key, project_name, project_description)),
                ),
                ("data_type", text(setting.data_type)),
                ("category", text(setting.category)),
                ("description", text(setting.description)),
                ("is_sensitive", Sql::Bool(setting.is_sensitive)),
                ("is_active", Sql::Bool(true)),
                ("created_by", text(created_by)),
                ("updated_by", text(created_by)),
                ("created_at", now()),
                ("updated_at", now()),
            ],
        ));
    }

    out.push(String::new());
    out.join("\n")
}

/// The model's own words for the two identity keys; empty for everything else.
fn value_for(key: &str, project_name: &str, project_description: &str) -> String {
    match key {
        "app_name" => project_name.to_string(),
        "app_description" => project_description.to_string(),
        _ => String::new(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn sql() -> String {
        build_system_seed_sql(&SystemSeedOptions {
            project_name: "acme",
            project_description: "Order tracking for Acme",
            created_by: "system",
        })
    }

    #[test]
    fn the_identity_keys_carry_the_models_own_words() {
        let sql = sql();
        assert!(sql.contains("'app_name', 'acme'"));
        assert!(sql.contains("'app_description', 'Order tracking for Acme'"));
    }

    #[test]
    fn every_other_key_is_seeded_empty() {
        // The rows exist so the admin screen can list what is settable. A
        // seeded value would silently override whatever the deployment put in
        // its settings block, which is the opposite of what an operator asked
        // for by setting an environment variable.
        let sql = sql();
        for key in ["ai_base_url", "ai_model", "ai_api_key", "electric_url"] {
            assert!(
                sql.contains(&format!("'{key}', ''")),
                "{key} should be seeded empty"
            );
        }
    }

    #[test]
    fn a_quote_in_the_project_name_does_not_escape_the_literal() {
        let sql = build_system_seed_sql(&SystemSeedOptions {
            project_name: "O'Brien Logistics",
            project_description: "It's a description",
            created_by: "system",
        });
        assert!(sql.contains("'O''Brien Logistics'"));
        assert!(sql.contains("'It''s a description'"));
    }

    #[test]
    fn the_ids_are_stable_across_runs_and_scoped_to_the_project() {
        // Re-running the generator must produce the same file, or every
        // regeneration would insert a second row for every key.
        assert_eq!(sql(), sql());

        let other = build_system_seed_sql(&SystemSeedOptions {
            project_name: "other",
            project_description: "Order tracking for Acme",
            created_by: "system",
        });
        let id_of = |text: &str| {
            text.lines()
                .find(|line| line.contains("'app_name'"))
                .and_then(|line| line.split('\'').nth(1).map(str::to_string))
                .expect("an app_name row")
        };
        assert_ne!(
            id_of(&sql()),
            id_of(&other),
            "two projects must not share a row id"
        );
    }

    #[test]
    fn every_statement_is_re_runnable() {
        let sql = sql();
        let inserts = sql.matches("INSERT INTO sys_system").count();
        assert_eq!(inserts, SETTING_COUNT);
        let guarded = sql
            .lines()
            .filter(|line| line.trim() == "ON CONFLICT DO NOTHING;")
            .count();
        assert_eq!(
            guarded, inserts,
            "every INSERT needs its own conflict clause"
        );
    }
}
