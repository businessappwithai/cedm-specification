/**
 * `seed/business.sql` — demonstration records for the model's own entities.
 *
 * A freshly migrated application has a complete dictionary and empty business
 * tables, so `docker compose up` opens on a dashboard of empty lists. This is
 * what puts something behind them.
 *
 * **Nothing here is invented.** Every value comes from what the model declares,
 * and the database's own constraints are what prove it:
 *
 * | Column | Where the value comes from |
 * |---|---|
 * | bound to an enum    | that enum's declared values, in order |
 * | the status of a state machine | the machine's `initial` state |
 * | a foreign key | the id of a row this file has already inserted |
 * | anything else | the entity's own display name and the row's number |
 *
 * That matters most for the first two. A status column seeded with a word the
 * model never declared is a record in a state no transition leads out of: the
 * guard refuses every move, and the workflow the application was generated to
 * demonstrate is dead on exactly the rows meant to demonstrate it.
 *
 * **Referential integrity is enforced, not suspended.** The sibling's seed opens
 * with `SET session_replication_role = replica` and inserts in any order; this
 * one sorts the entities so a row is written after everything it points at, and
 * leaves the constraints on. If the insert order were wrong the seed would fail
 * loudly rather than leave a table full of references to nothing — which is the
 * only difference between demonstration data and data that merely looks real.
 *
 * A column whose target the model does not declare is written NULL. A uuid that
 * joins to nothing is worse than an empty cell: it renders as a broken lookup
 * and reads as a data problem rather than a modelling one.
 */

import type { BusEntity, BusEntityAttribute } from "@appwithai/core/types";
import { foreignKeyTargetTable, ReferenceType } from "@appwithai/core/types";
import type { CompiledWorkflow } from "../../workflows/state-machine";
import { insert, raw, type SqlValue, uuidv5 } from "./dictionary-seed";

export interface BusinessSeedOptions {
  projectName: string;
  entities: BusEntity[];
  /** Declared `oneToMany` links — the only ones the schema constrains. */
  relationships: Array<{ sourceEntity: string; targetEntity: string; cardinality: string }>;
  /** State machines, for the initial state of a status column. */
  workflows?: CompiledWorkflow[];
  /**
   * Enum declarations with their ids.
   *
   * Resolved through `attribute.referenceId` rather than read off the attribute
   * directly: that id is what `sys_column.sys_reference_id` carries and what
   * the form renders its dropdown from, so a value chosen any other way could
   * be one the control does not offer.
   */
  modelEnums?: Array<{ referenceId: number; values: string[] }>;
  /** Rows per entity. Enough to show a list, a lookup and a detail page. */
  rowsPerEntity?: number;
}

const NOW = raw("NOW()");

/** Enough to fill a grid, show a second page of nothing, and offer a lookup. */
const DEFAULT_ROWS = 5;

/** Columns the schema fills in, which a seed must not write. */
const MANAGED = new Set([
  "created_at",
  "updated_at",
  "deleted_at",
  "version",
  "workflow_status",
  "doc_status_message",
]);

export function buildBusinessSeedSql(options: BusinessSeedOptions): string {
  const { projectName, entities } = options;
  const rows = options.rowsPerEntity ?? DEFAULT_ROWS;
  const tables = new Set(entities.map((entity) => entity.tableName));

  const out: string[] = [];
  out.push(`-- Demonstration records for ${projectName}.`);
  out.push("--");
  out.push("-- Generated by @appwithai/generator — do not edit by hand; regenerate instead.");
  out.push("-- Applied by `cargo loco task seed_business`.");
  out.push("--");
  out.push("-- Every value is the model's own: a column with an enum takes a declared value, a");
  out.push("-- status column takes its machine's initial state, and a foreign key takes the");
  out.push("-- id of a row inserted above it. Referential integrity is left switched on —");
  out.push("-- the entities are ordered so that it holds — so a seed that got this wrong");
  out.push("-- would fail rather than fill the tables with references to nothing.");
  out.push("--");
  out.push("-- Ids are deterministic, and every statement is `ON CONFLICT DO NOTHING`, so");
  out.push("-- re-running adds nothing and regenerating does not duplicate the rows.");

  if (entities.length === 0) {
    out.push("--");
    out.push("-- This model declares no entities. The file is still emitted:");
    out.push("-- `seed_business.rs` embeds it with include_str!, resolved at compile time.");
    out.push("");
    return out.join("\n");
  }

  const { ordered, deferred } = orderByDependency(entities, options.relationships);
  const initialStates = statusStates(options.workflows ?? [], entities);
  const enumValues = new Map(
    (options.modelEnums ?? []).map((declared) => [declared.referenceId, declared.values])
  );

  /** `bus_compound` row 2 → its id. Deterministic, so re-running is a no-op. */
  const rowId = (tableName: string, index: number) =>
    uuidv5(`${projectName}:business:${tableName}:${index}`);

  for (const entity of ordered) {
    out.push("");
    out.push(`-- ${entity.displayName} (${entity.tableName})`);

    const deferredHere = deferred.get(entity.tableName) ?? new Set<string>();

    for (let index = 0; index < rows; index++) {
      const values: Record<string, SqlValue> = {
        [entity.primaryKey ?? "id"]: rowId(entity.tableName, index),
      };

      const machine = initialStates.get(entity.tableName);

      for (const attribute of entity.attributes) {
        const column = attribute.columnName;
        if (column === (entity.primaryKey ?? "id") || MANAGED.has(column)) continue;

        // Deferred because the two entities point at each other: written by the
        // trailing UPDATE below, once both rows exist.
        if (deferredHere.has(column)) continue;

        values[column] = valueFor(attribute, {
          entity,
          index,
          rows,
          tables,
          rowId,
          enumValues,
          initialState: machine,
        });
      }

      // A machine recorded against `workflow_status` writes a column the loop
      // above skips as managed — the schema gives it a 'none' default, and a
      // record left at that default is in a state the diagram never drew.
      if (machine && machine.column === "workflow_status") {
        values.workflow_status = machine.state;
      }

      // Inserted directly, so the promotion that would normally settle this
      // never runs and the column keeps its 'draft' default — a DRAFT badge on
      // every record in a demonstration of finished data. These rows are final.
      values.doc_status = "final";
      values.created_at = NOW;
      values.updated_at = NOW;

      out.push(insert(entity.tableName, values));
    }
  }

  const updates = deferredUpdates(ordered, deferred, tables, rows, rowId);
  if (updates.length > 0) {
    out.push("");
    out.push(`-- ${"-".repeat(74)}`);
    out.push("-- References that could not be written with the row");
    out.push(`-- ${"-".repeat(74)}`);
    out.push("--");
    out.push("-- These entities point at each other, so neither can be inserted second.");
    out.push("-- The row goes in without the reference and the reference is set here, once");
    out.push("-- both sides exist — the same order the dictionary seed uses for");
    out.push("-- `sys_tab.link_column_id`.");
    out.push(...updates);
  }

  out.push("");
  return out.join("\n");
}

interface ValueContext {
  entity: BusEntity;
  index: number;
  rows: number;
  tables: ReadonlySet<string>;
  rowId: (tableName: string, index: number) => string;
  /** `sys_reference_id` → the values that reference offers. */
  enumValues: ReadonlyMap<number, string[]>;
  /** The state a record of this entity starts in, when it has a machine. */
  initialState?: { column: string; state: string };
}

/**
 * One column's value, derived from what the model says about it.
 *
 * The order of the checks is the point. A column bound to an enum is answered
 * from that enum whatever else its name suggests, and a status column backing a
 * machine is answered from the machine — both before any derivation from the
 * column's type, because those two are the cases where a plausible-looking
 * value is *invalid* rather than merely unrealistic.
 */
function valueFor(attribute: BusEntityAttribute, context: ValueContext): SqlValue {
  const { index } = context;
  const column = attribute.columnName;

  // A state machine's initial state. Any other value is a record the guard
  // cannot move, because the diagram draws no edge out of a state it never
  // declared.
  if (context.initialState && column === context.initialState.column) {
    return context.initialState.state;
  }

  // The model's own dictionary for this column. The dropdown offers exactly
  // these, and a rule keyed on a status only fires on one of them.
  const declared = context.enumValues.get(attribute.referenceId);
  if (declared && declared.length > 0) {
    return declared[index % declared.length] as string;
  }

  if (attribute.isForeignKey || isReferenceColumn(column)) {
    const target = foreignKeyTargetTable(column, context.tables);
    // NULL rather than a uuid that joins to nothing: an empty lookup reads as
    // "not set", a dangling one reads as corruption.
    if (!target) return null;
    return context.rowId(target, index % context.rows);
  }

  // The control the dictionary stamped on this column, which is the same answer
  // the form and the grid render from. Reading `semanticType` instead would
  // miss every column the model wrote as a plain `string` and the dictionary
  // resolved by name — `email`, `phone` and `website` all arrive that way — and
  // the seed would write "Email 1" into a column the form validates as an
  // address.
  switch (attribute.referenceId) {
    case ReferenceType.EMAIL:
      return `${slug(context.entity.displayName)}.${index + 1}@example.com`;
    case ReferenceType.URL:
      return `https://example.com/${slug(context.entity.displayName)}/${index + 1}`;
    case ReferenceType.PHONE:
      return `+1-555-01${String(index + 10).padStart(2, "0")}`;
    case ReferenceType.COLOR:
      return "#4a5568";
    case ReferenceType.PASSWORD:
      // Never a usable credential in seed data, and never a real-looking one.
      return null;
    default:
      break;
  }

  // An optional date or timestamp is left empty, and this is the one heuristic
  // in the file. A date column that the model does not require is almost always
  // recording that something happened — `cancelled_at`, `approved_on`,
  // `completed_at` — so filling it puts the row in two states at once: a
  // booking in `held` with a cancellation time contradicts itself, and reads as
  // a bug in the application rather than in its sample data. A required date is
  // part of what the record *is*, so it is filled.
  if (!attribute.required && (attribute.type === "date" || attribute.type === "datetime")) {
    return null;
  }

  switch (attribute.type) {
    case "integer":
      return index + 1;
    case "decimal":
      // Raw, and fixed at two places: a JavaScript number renders 42 for 42.00
      // and 52.5 for 52.50, so writing it as a literal would put a different
      // string in the file than the Rust generator does — which `bun run
      // parity` is exactly the gate against.
      return raw(((index + 1) * 10.5).toFixed(2));
    case "boolean":
      return index % 2 === 0;
    case "date":
      return `2026-0${(index % 9) + 1}-15`;
    case "datetime":
      return `2026-0${(index % 9) + 1}-15T09:00:00Z`;
    case "json":
      return "{}";
    default:
      return label(attribute, context);
  }
}

/**
 * The text a string column gets: the thing's own name and which one it is.
 *
 * Deliberately not a vocabulary of invented nouns. "Compound 3" is honestly a
 * placeholder and reads as one; "Acetaminophen" reads as data somebody entered,
 * and a reader cannot tell a seeded row from a real one.
 */
function label(attribute: BusEntityAttribute, context: ValueContext): string {
  const base = `${context.entity.displayName} ${context.index + 1}`;
  const text = attribute.isIdentifier ? base : `${attribute.displayName} ${context.index + 1}`;
  // Unique columns must not collide, and a maxLength must not be exceeded — a
  // seed that violates either fails the insert rather than the row.
  const scoped = attribute.unique ? `${text} (${context.entity.tableName})` : text;
  const limit = attribute.maxLength ?? 255;
  return scoped.length > limit ? scoped.slice(0, limit) : scoped;
}

/** `Clinical Trial` → `clinical-trial`, for an address a reader can type. */
function slug(displayName: string): string {
  return displayName
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

/** A uuid column that names something, whether or not the ERD marked it FK. */
function isReferenceColumn(column: string): boolean {
  return column.endsWith("_id") || column.endsWith("_by");
}

/**
 * Physical table → the status column and the state a record starts in.
 *
 * The column is resolved the same way `statusFieldFor` resolves it for
 * `seed/transitions.sql`: the entity's own `status` when it declares one, and
 * `workflow_status` otherwise. Naming a different column here would seed a
 * state onto one column while the guard reads the other, and every record
 * would be stuck in the `none` the schema defaults to.
 */
function statusStates(
  workflows: CompiledWorkflow[],
  entities: BusEntity[]
): Map<string, { column: string; state: string }> {
  const columnsByTable = new Map(
    entities.map((entity) => [
      entity.tableName,
      new Set(entity.attributes.map((attribute) => attribute.columnName)),
    ])
  );

  const states = new Map<string, { column: string; state: string }>();
  for (const workflow of workflows) {
    if (!workflow.initial) continue;
    const column = columnsByTable.get(workflow.tableName)?.has("status")
      ? "status"
      : "workflow_status";
    states.set(workflow.tableName, { column, state: workflow.initial });
  }
  return states;
}

/**
 * Entities in an order where a row is written after everything it points at.
 *
 * Only declared `oneToMany` links are considered, because those are the only
 * ones the schema constrains — a column the ERD marks `FK` but draws no line
 * for is a reference the dictionary describes and the database does not
 * enforce, so it cannot fail an insert and cannot constrain the order.
 *
 * A cycle is not an error: two entities may legitimately point at each other.
 * The edge that closes it is dropped from the ordering and its column named in
 * `deferred`, to be written by an UPDATE once both rows exist.
 */
function orderByDependency(
  entities: BusEntity[],
  relationships: BusinessSeedOptions["relationships"]
): { ordered: BusEntity[]; deferred: Map<string, Set<string>> } {
  const byTable = new Map(entities.map((entity) => [entity.tableName, entity]));
  const deferred = new Map<string, Set<string>>();

  /** `bus_target` → the tables it must be written after. */
  const dependsOn = new Map<string, Map<string, string>>();
  for (const relationship of relationships) {
    if (relationship.cardinality !== "oneToMany") continue;
    const parent = `bus_${snake(relationship.sourceEntity)}`;
    const child = `bus_${snake(relationship.targetEntity)}`;
    if (!byTable.has(parent) || !byTable.has(child) || parent === child) continue;
    const edges = dependsOn.get(child) ?? new Map<string, string>();
    edges.set(parent, `${snake(relationship.sourceEntity)}_id`);
    dependsOn.set(child, edges);
  }

  const ordered: BusEntity[] = [];
  const done = new Set<string>();
  const onStack = new Set<string>();

  const visit = (tableName: string) => {
    if (done.has(tableName)) return;
    if (onStack.has(tableName)) return;
    onStack.add(tableName);

    for (const [parent, column] of dependsOn.get(tableName) ?? []) {
      if (onStack.has(parent)) {
        // The edge that closes the cycle. Written by the trailing UPDATE.
        const columns = deferred.get(tableName) ?? new Set<string>();
        columns.add(column);
        deferred.set(tableName, columns);
        continue;
      }
      visit(parent);
    }

    onStack.delete(tableName);
    done.add(tableName);
    const entity = byTable.get(tableName);
    if (entity) ordered.push(entity);
  };

  // Declaration order for everything the graph does not constrain, so a model
  // with no relationships emits the file it always did.
  for (const entity of entities) visit(entity.tableName);

  return { ordered, deferred };
}

/** `UPDATE` statements for the references a cycle would not let us insert. */
function deferredUpdates(
  ordered: BusEntity[],
  deferred: Map<string, Set<string>>,
  tables: ReadonlySet<string>,
  rows: number,
  rowId: (tableName: string, index: number) => string
): string[] {
  const out: string[] = [];
  for (const entity of ordered) {
    const columns = deferred.get(entity.tableName);
    if (!columns) continue;
    for (const column of columns) {
      const target = foreignKeyTargetTable(column, tables);
      if (!target) continue;
      for (let index = 0; index < rows; index++) {
        out.push(
          `UPDATE ${entity.tableName} SET ${column} = '${rowId(target, index % rows)}'` +
            ` WHERE id = '${rowId(entity.tableName, index)}' AND ${column} IS NULL;`
        );
      }
    }
  }
  return out;
}

/** The ERD parser's own table naming, for resolving a relationship's ends. */
function snake(entityName: string): string {
  return entityName
    .replace(/([A-Z]+)([A-Z][a-z])/g, "$1_$2")
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .replace(/[-\s]+/g, "_")
    .toLowerCase();
}

export default buildBusinessSeedSql;
