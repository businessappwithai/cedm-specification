/**
 * `seed/access.sql` — what the model's `rbac` compiles to.
 *
 * Two things reach the database: the roles the model named, and the rules that
 * close an operation to them.
 *
 * The rules go in `sys_operation_access`, deliberately not `sys_access`. That
 * is a *grant* table feeding `sys_refresh_dictionary_scope()`, where a table
 * with no rows is visible to every role and the first row narrows it to that
 * role alone. Seeding a rule closing `Order` `delete` to `admin` there would hide the
 * Order window from everybody but admin — a restriction on deleting silently
 * becoming a restriction on looking.
 *
 * A `(table_name, operation)` pair with no row is unrestricted. That is what
 * makes the rules additive: a model declaring no access rules generates exactly
 * what it did before this file existed.
 */

import type { CompiledRbac } from "../../rbac";
import { deriveAccess } from "../../rbac/roles";
import { insert, lit, raw, uuidv5 } from "./dictionary-seed";
import { statusFieldFor } from "./transitions-seed";

export interface AccessSeedOptions {
  projectName: string;
  rbac: CompiledRbac;
  /**
   * The entities the dictionary describes, so a declared role can be granted
   * the windows it needs to open. Omitted, the roles are created with no
   * `sys_access` row at all — see the grants section below for why that makes
   * them useless.
   */
  entities?: { name: string; tableName: string; windowOwner?: string }[];
  /**
   * Physical table name → its column names.
   *
   * A transition rule has to name the same status column the transition itself
   * writes, or the guard reads a column nothing sets and every restriction on
   * it is inert. Both seeds resolve it through `statusFieldFor`.
   */
  columnsByTable?: Map<string, string[]>;
  /** Value written to every `created_by` / `updated_by`. */
  createdBy?: string;
}

const NOW = raw("NOW()");

/**
 * The roles `dictionary.sql` already seeds.
 *
 * A model that writes `role:administrator` means that one; adding a second row
 * of the same name would give the account whichever the lookup returned first.
 */
const BUILT_IN_ROLE_NAMES = new Set(["administrator", "user"]);

export function buildAccessSeedSql(options: AccessSeedOptions): string {
  const { projectName, rbac } = options;
  const createdBy = options.createdBy ?? "system";
  const id = (kind: string, ...parts: string[]) =>
    uuidv5(`${projectName}:${kind}:${parts.join(":")}`);

  const out: string[] = [];
  const section = (title: string) => {
    out.push("");
    out.push(`-- ${"-".repeat(74)}`);
    out.push(`-- ${title}`);
    out.push(`-- ${"-".repeat(74)}`);
  };

  out.push(`-- Access rules for ${projectName}, compiled from the model's access rules.`);
  out.push("--");
  out.push("-- Generated by @appwithai/generator — do not edit by hand; regenerate instead.");
  out.push("-- Applied by `cargo loco task seed_access` and by `cargo loco db seed`.");
  out.push("--");
  out.push("-- Every statement is `ON CONFLICT DO NOTHING` over a deterministic primary");
  out.push("-- key, so running this file twice is a no-op.");

  if (rbac.operations.length === 0 && rbac.transitions.length === 0) {
    out.push("--");
    out.push("-- This model declares no access rules, so every operation stays open to any");
    out.push("-- authenticated caller. The file is still emitted: `seed_access.rs`");
    out.push("-- embeds it with include_str!, which is resolved at compile time.");
    out.push("");
    return out.join("\n");
  }

  // ── Roles ───────────────────────────────────────────────────────────────
  /* The same `projectId` the backend context passes, so the two derivations
     agree on every field — only `roles` is read here, but a divergence would
     be invisible until something else started reading `users`. */
  const derived = deriveAccess(rbac, {
    projectId: projectName.toLowerCase().replace(/[^a-z0-9]+/g, "-"),
  });
  const declaredRoles = derived.roles.filter(
    (role) => !BUILT_IN_ROLE_NAMES.has(role.name.toLowerCase())
  );

  if (declaredRoles.length > 0) {
    section("Roles the model named");
    for (const role of declaredRoles) {
      out.push(
        insert("sys_role", {
          sys_role_id: id("role", role.name),
          name: role.name,
          description: role.description,
          user_level: role.userLevel,
          is_master_role: role.isAdmin,
          is_can_export: true,
          is_can_report: true,
          is_personal_lock: false,
          is_personal_access: false,
          max_query_records: 0,
          is_show_accounting: false,
          entity_type: "U",
          is_active: true,
          created_by: createdBy,
          updated_by: createdBy,
          created_at: NOW,
          updated_at: NOW,
        })
      );
    }
  }

  // ── What those roles may open ───────────────────────────────────────────
  /*
   * A role with no `sys_access` row is refused by the *first* of the three
   * gates, before either of the tables below is consulted. The seeded
   * demonstration accounts were in exactly that state: signing in as the
   * Researcher gave an empty dashboard, `windows: []` from
   * `/api/me/permissions`, and 403 on every entity — including reads, and
   * including the transitions its own access rules granted it.
   *
   * So each declared role is granted the same windows the built-in `User` role
   * gets, and the two tables below are what narrow it. That is what the
   * rules' additive semantics mean: a rule granting `Order` `delete` to x closes
   * deleting to everyone but x, and says nothing about looking at an Order.
   *
   * The grant names the role through a subselect for the same reason
   * `dictionary.sql` does — the role row is inserted a few lines above and an
   * administrator may since have renamed it.
   */
  const entities = options.entities ?? [];
  if (declaredRoles.length > 0 && entities.length > 0) {
    section("What the model's roles may open (sys_access)");
    const tableNameByEntity = new Map(entities.map((entity) => [entity.name, entity.tableName]));
    const ownerByName = new Map(entities.map((entity) => [entity.name, entity.windowOwner]));
    /** The entity whose window an entity is reached through: follow `windowOwner` to the top. */
    const windowRoot = (name: string): string => {
      const seen = new Set<string>();
      let current = name;
      for (;;) {
        const next = ownerByName.get(current) ?? current;
        if (next === current || seen.has(current)) return current;
        seen.add(current);
        current = next;
      }
    };
    for (const role of declaredRoles) {
      for (const entity of entities) {
        // A child entity has no window of its own; its rows are reached
        // through the parent's — the topmost one's, for a line item of a line
        // item — which is the window that has to be granted.
        const windowTable = tableNameByEntity.get(windowRoot(entity.name)) ?? entity.tableName;
        out.push(
          insert("sys_access", {
            sys_access_id: id("access", role.name, entity.tableName),
            sys_role_id: raw(`(SELECT sys_role_id FROM sys_role WHERE name = ${lit(role.name)})`),
            sys_table_id: id("table", entity.tableName),
            sys_window_id: id("window", windowTable),
            access_type_table: "W",
            is_read_only: false,
            is_exclude: false,
            entity_type: "U",
            is_active: true,
            created_by: createdBy,
            updated_by: createdBy,
            created_at: NOW,
            updated_at: NOW,
          })
        );
      }
    }
  }

  // ── Operation rules ─────────────────────────────────────────────────────
  if (rbac.operations.length > 0) {
    section("Per-operation access (sys_operation_access)");
    for (const rule of rbac.operations) {
      for (const role of rule.roles) {
        out.push(
          insert("sys_operation_access", {
            sys_operation_access_id: id("operation_access", rule.tableName, rule.operation, role),
            table_name: rule.tableName,
            operation: rule.operation,
            // The author's spelling, not the title-cased role name: the guard
            // folds case when it compares, and the admin UI should show what
            // the model actually said.
            role_name: role,
            // Marks the row as the model's. A rule added in the running
            // application is unmarked, so regeneration can replace what it owns
            // without discarding what an administrator added.
            is_model_managed: true,
            is_active: true,
            created_at: NOW,
            updated_at: NOW,
          })
        );
      }
    }
  }

  // ── Transition rules ────────────────────────────────────────────────────
  if (rbac.transitions.length > 0) {
    section("Per-transition access (sys_transition_access)");
    for (const rule of rbac.transitions) {
      for (const edge of rule.edges) {
        for (const role of rule.roles) {
          out.push(
            insert("sys_transition_access", {
              sys_transition_access_id: id(
                "transition_access",
                rule.tableName,
                rule.transition,
                edge.from,
                edge.to,
                role
              ),
              table_name: rule.tableName,
              transition: rule.transition,
              // The same column `seed/transitions.sql` recorded the edge
              // against. Reading a different one would leave the rule matching
              // nothing.
              status_field: statusFieldFor(rule.tableName, options.columnsByTable ?? new Map()),
              from_state: edge.from,
              to_state: edge.to,
              role_name: role,
              is_model_managed: true,
              is_active: true,
              created_at: NOW,
              updated_at: NOW,
            })
          );
        }
      }
    }
  }

  out.push("");
  return out.join("\n");
}

export default buildAccessSeedSql;
