/**
 * `seed/rules.sql` — what the model's `rules` compile to.
 *
 * A rule is a decision graph. `compileRuleDeclarations` turns it into a GoRules
 * JDM document; this writes that document into `sys_rule_definitions`, which is
 * the table `bus::load_entity_jdms` reads on every business write. Before this
 * the table existed, the controller read it, the admin editor edited it — and
 * nothing ever put a row in it, so a rule drawn in the design phase reached the
 * generated application and did nothing.
 *
 * ## One file, two conflict policies
 *
 * `seed_rules` must be safe to re-run against a database an administrator has
 * been editing, so it must not overwrite. But a model whose rule *changed* has
 * to be able to reach that database somehow, or the only way to pick up an
 * edited decision graph is to drop the database.
 *
 * Both live in this one file, selected by a session setting:
 *
 * ```sql
 * ON CONFLICT (...) DO UPDATE SET ...
 *   WHERE current_setting('appwithai.rules_overwrite', true) = 'on'
 * ```
 *
 * `current_setting(name, true)` is NULL when the setting is absent, so the
 * WHERE is false and the conflict is skipped — ordinary `DO NOTHING`
 * behaviour, and what `cargo loco task seed_rules` gets. `POST /api/rules/migrate`
 * opens a transaction, sets it with `SET LOCAL`, and applies the same file;
 * every row is then overwritten with the model's version.
 *
 * The alternative was to carry the JDM twice — once as SQL for the seed, once
 * as a Rust array for the endpoint — and JDM documents are the largest thing
 * this generator emits. Two copies of them would be two copies to drift.
 */

import type { CompiledRule } from "../../rules";
import { insert, raw, uuidv5 } from "./dictionary-seed";

export interface RulesSeedOptions {
  projectName: string;
  rules: CompiledRule[];
  /** Value written to `created_by` / `updated_by`. */
  createdBy?: string;
}

const NOW = raw("NOW()");

/**
 * The conflict clause, appended in place of the `insert()` helper's own.
 *
 * `insert()` writes a bare `ON CONFLICT DO NOTHING`, which is right for the
 * dictionary. Rules need the conditional form, so the statement is rebuilt
 * here rather than given a second mode nothing else would use.
 */
const CONFLICT = [
  "ON CONFLICT (entity_name, operation, rule_name) DO UPDATE",
  "  SET jdm_content = EXCLUDED.jdm_content,",
  "      version     = sys_rule_definitions.version + 1,",
  "      is_active   = TRUE,",
  "      updated_by  = EXCLUDED.updated_by,",
  "      updated_at  = NOW()",
  "  WHERE current_setting('appwithai.rules_overwrite', true) = 'on';",
].join("\n");

export function buildRulesSeedSql(options: RulesSeedOptions): string {
  const { projectName, rules } = options;
  const createdBy = options.createdBy ?? "system";

  const out: string[] = [];
  out.push(`-- Business rules for ${projectName}, compiled from the model's rules.`);
  out.push("--");
  out.push("-- Generated by @appwithai/generator — do not edit by hand; regenerate instead.");
  out.push("-- Applied by `cargo loco task seed_rules` and by `cargo loco db seed`.");
  out.push("--");
  out.push("-- Each statement conflicts on (entity_name, operation, rule_name) and updates");
  out.push("-- only when `appwithai.rules_overwrite` is set to 'on' — which the seed task");
  out.push("-- does not set and `POST /api/rules/migrate` does. Seeding therefore installs");
  out.push("-- what is missing and leaves an administrator's edits alone; migrating");
  out.push("-- replaces them with the model's version.");

  if (rules.length === 0) {
    out.push("--");
    out.push("-- This model declares no rules. The file is still emitted:");
    out.push("-- `seed_rules.rs` embeds it with include_str!, which is resolved at");
    out.push("-- compile time, so a crate without it does not build.");
    out.push("");
    return out.join("\n");
  }

  for (const rule of rules) {
    out.push("");
    out.push(`-- ${rule.name} — ${rule.entity}.${rule.event} (priority ${rule.priority})`);
    // Built from `insert()` so the column list and literal escaping are the
    // dictionary seed's, then re-terminated with the conditional conflict
    // clause above.
    const statement = insert("sys_rule_definitions", {
      id: uuidv5(`${projectName}:rule:${rule.tableName}:${rule.operation}:${rule.name}`),
      // The physical table, not the ERD name: `load_entity_jdms` binds
      // `meta.table_name` when it looks a rule up, so an entity-named row is a
      // row that never fires.
      entity_name: rule.tableName,
      rule_name: rule.name,
      operation: rule.operation,
      jdm_content: rule.jdmContent,
      version: 1,
      is_active: true,
      created_by: createdBy,
      updated_by: createdBy,
      created_at: NOW,
      updated_at: NOW,
    }).replace(/ON CONFLICT DO NOTHING;$/, CONFLICT);
    out.push(statement);
  }

  out.push("");
  return out.join("\n");
}

export default buildRulesSeedSql;
